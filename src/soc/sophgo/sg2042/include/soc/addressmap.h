#ifndef SOC_SOPHGO_SG2042_ADDRESSMAP_H
#define SOC_SOPHGO_SG2042_ADDRESSMAP_H

#define SG2042_ZSBL_BASE	0x40000000
#define SG2042_PCIE_BASE	0xc0000000
#define SG2042_PCIE_END		0x100000000
#define SG2042_SYS_CTRL		0x7030010000
#define SG2042_TOP_CONF_INFO	(SG2042_SYS_CTRL + 0x4)
#define SG2042_DDR_SIZE		(SG2042_SYS_CTRL + 0x54)
#define SG2042_BOARD_TYPE	(SG2042_SYS_CTRL + 0x23c)
#define SG2042_MP_STATUS(i)	(SG2042_SYS_CTRL + 0x380 + (i) * 8)
#define SG2042_MP_CONTROL(i)	(SG2042_SYS_CTRL + 0x384 + (i) * 8)
#define SG2042_TOP_RESET	(SG2042_SYS_CTRL + 0x3000)
#define SG2042_UART0		0x7040000000
#define SG2042_MSWI		0x7094000000
#define SG2042_MTIMER		0x70ac004000

#endif
